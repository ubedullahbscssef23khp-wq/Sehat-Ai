# --- B. EMERGENCY PRE-SCREEN BYPASS INVARIANT ---
def test_invariant_emergency_bypass_skips_llm(tmp_path: Path) -> None:
    pattern = make_pattern("T-INV-PRE-1", "synthetic bypass trigger")
    # Must be APPROVED to activate
    pattern.review_status = ReviewStatus.APPROVED
    harness = OrchestratorHarness(tmp_path, patterns=[pattern]) # Provider queue is empty, would raise LLMUnavailable if called
    
    import asyncio
    session = harness.orchestrator.create_session()
    response = asyncio.run(
        harness.orchestrator.handle_message(session.id, "I have a synthetic bypass trigger right now")
    )
    
    assert response.triage.level is TriageLevel.EMERGENCY
    assert "T-INV-PRE-1" in response.triage.fired_rule_ids
    assert len(harness.provider.requests) == 0 # LLM NOT called
    assert harness.orchestrator.get_session(session.id).status is SessionStatus.ESCALATED

# --- C. LLM CANNOT OVERRIDE TRIAGE ---
def test_invariant_llm_cannot_override_triage(tmp_path: Path) -> None:
    # LLM outputs a case, we evaluate deterministic rules.
    # We will make sure the text generated by LLM during composition doesn't change triage.
    # Wait, the LLM generates a composition string. It doesn't generate triage.
    # The extraction generates a StructuredCase. Triage is purely deterministic based on StructuredCase.
    # Let's extract a case that maps to routine, but LLM adds confidence=1.0 or something. 
    # Actually, composition outputs just text.
    harness = OrchestratorHarness(tmp_path, scripts=(case_json(), "You must go to the emergency room immediately!"))
    import asyncio
    session = harness.orchestrator.create_session()
    response = asyncio.run(harness.orchestrator.handle_message(session.id, "routine synthetic issue"))
    
    assert response.triage.level is TriageLevel.SELF_CARE
    # The output text might say emergency but triage level is deterministic
    assert response.triage.level != TriageLevel.EMERGENCY

# --- D. OUTPUT POLICY CANNOT OVERRIDE TRIAGE ---
def test_invariant_output_policy_cannot_override_triage(tmp_path: Path) -> None:
    # If the LLM generates something violating policy, it falls back to a safe phrase.
    # This shouldn't change the TriageDecision object.
    harness = OrchestratorHarness(tmp_path, scripts=(case_json(), "You have a synthetic disease."))
    import asyncio
    session = harness.orchestrator.create_session()
    response = asyncio.run(harness.orchestrator.handle_message(session.id, "synthetic issue"))
    
    assert response.triage.level is TriageLevel.SELF_CARE
    assert "you have" not in response.user_message.en.lower() # Fallback used
    # Triage remained exactly what the engine decided

# --- E. UNKNOWN RED-FLAG SIGNAL FAIL-CLOSED ---
from unittest.mock import patch
def test_invariant_unknown_signal_fail_closed(tmp_path: Path) -> None:
    with patch('app.safety.signals._ALLOWED_SIGNALS', {'KNOWN_SYNTHETIC_SIGNAL'}):
        # Case reports an unknown and a known signal
        case_dict = json.loads(case_json())
        case_dict["red_flag_signals"] = ["KNOWN_SYNTHETIC_SIGNAL", "UNKNOWN_ROGUE_SIGNAL"]
        
        rule = make_signal_rule("T-R-KNOWN", "KNOWN_SYNTHETIC_SIGNAL", SafetyLevel.URGENT)
        # Attempt to make a rule for the unknown (shouldn't matter as extraction is filtered)
        rule_unknown = make_signal_rule("T-R-UNK", "UNKNOWN_ROGUE_SIGNAL", SafetyLevel.EMERGENCY)
        
        harness = OrchestratorHarness(tmp_path, scripts=(json.dumps(case_dict), "safe output"), rules=[rule, rule_unknown])
        import asyncio
        session = harness.orchestrator.create_session()
        response = asyncio.run(harness.orchestrator.handle_message(session.id, "synthetic message"))
        
        # Only the known signal triggers
        assert response.triage.level is TriageLevel.URGENT_SAME_DAY
        assert "T-R-KNOWN" in response.triage.fired_rule_ids
        assert "T-R-UNK" not in response.triage.fired_rule_ids

