# --- J. CLINICIAN SUMMARY BOUNDARY ---
def test_invariant_clinician_summary_boundary(tmp_path: Path) -> None:
    import asyncio
    # 1. Normal final guidance -> has summary
    harness1 = OrchestratorHarness(tmp_path, scripts=(case_json(), "output"))
    sess1 = harness1.orchestrator.create_session()
    resp1 = asyncio.run(harness1.orchestrator.handle_message(sess1.id, "synthetic"))
    assert resp1.clinician_summary is not None
    assert len(harness1.provider.requests) == 2 # 1 extract, 1 compose
    
    # 2. Emergency bypass -> has summary (deterministically constructed)
    pat = make_pattern("P-1", "bypass")
    pat.review_status = ReviewStatus.APPROVED
    harness2 = OrchestratorHarness(tmp_path, patterns=[pat])
    sess2 = harness2.orchestrator.create_session()
    resp2 = asyncio.run(harness2.orchestrator.handle_message(sess2.id, "bypass"))
    assert resp2.clinician_summary is None
    assert len(harness2.provider.requests) == 0 # NO LLM for emergency bypass summary
    
    # 3. Follow-up only -> NO summary
    harness3 = OrchestratorHarness(tmp_path, scripts=(incomplete_case_json(), questions_json(1)))
    sess3 = harness3.orchestrator.create_session()
    resp3 = asyncio.run(harness3.orchestrator.handle_message(sess3.id, "synthetic"))
    assert resp3.clinician_summary is None

# --- K. TRACE PRIVACY INTEGRATION ---
def test_invariant_trace_privacy_excludes_sensitive(tmp_path: Path) -> None:
    raw_input = "extremely sensitive raw patient input text"
    harness = OrchestratorHarness(tmp_path, scripts=(case_json(), "output"))
    import asyncio
    sess = harness.orchestrator.create_session()
    asyncio.run(harness.orchestrator.handle_message(sess.id, raw_input))
    
    traces = TraceRepository(harness.session_factory).list_for_session(sess.id)
    # Check that raw_input is nowhere in any trace
    for trace in traces:
        dump = trace.model_dump_json()
        assert raw_input not in dump
        if trace.step == "extraction":
            # Input hash MUST be present and match
            assert trace.input_hash == hashlib.sha256(raw_input.encode("utf-8")).hexdigest()

